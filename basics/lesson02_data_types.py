# Lesson 2 - Data Types

# String
aircraft = "Airbus A350"

# Integer
speed = 905

# Float
temperature = -52.5

# Boolean
engine_running = True

print("Aircraft:", aircraft)
print("Speed:", speed)
print("Temperature:", temperature)
print("Engine Running:", engine_running)

print(type(aircraft))
print(type(speed))
print(type(temperature))
print(type(engine_running))
